# cryptography module doc.
#   https://cryptography.io/en/stable/hazmat/primitives/asymmetric/ec/
# 
# ec.derive_private_key(
#                       private_value (int) -> The secret scalar value,
#                       curve -> An instance of EllipticCurve
#                      )
#   returns an instance of EllipticCurvePrivateKey
#
# ec.SECP256E1() 
#   returns an instance of SECG curve secp256r1. Also called NIST P-256. (TF-M USES this curve, as explain in the tf-m doc:
#       https://trustedfirmware-m.readthedocs.io/en/latest/configuration/profiles/tfm_profile_medium.html)

private_number = int.from_bytes(DUMMY_IAK_BYTES, "big")
private_key = ec.derive_private_key(private_number, ec.SECP256R1())
public_key = private_key.public_key()

assert len(DUMMY_SIGNATURE_BYTES) == 64

